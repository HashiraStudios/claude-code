#!/usr/bin/env python3
"""Generate views for EVERY part of a kit, from a parts manifest.

  python kit_views.py --parts work/jeep/parts.json --master work/jeep/concept.png \
                      --out work/jeep/kit [--only body,wheel]

Each part is generated ALONE, conditioned on the master concept so the
palette and style stay identical across the kit. A part generated by
itself gets the entire resolution budget — which is the whole reason the
kit exists: a bumper that is 3% of a car render comes back as a smudge,
and the same bumper generated alone comes back with its winch drum,
shackles and bolt detail.

Writes <out>/<part_id>/concept.png + <out>/<part_id>/views/*.png, ready
for the shape stage.
"""
import argparse, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--parts", required=True, help="parts.json manifest")
    ap.add_argument("--master", required=True, help="whole-object concept, for style")
    ap.add_argument("--out", required=True)
    ap.add_argument("--only", help="comma-separated part ids to (re)generate")
    a = ap.parse_args()

    man = json.load(open(a.parts))
    wanted = set(a.only.split(",")) if a.only else None
    parts = [p for p in man["parts"] if not wanted or p["id"] in wanted]
    style = man.get("style", "")
    print(f"kit: {len(parts)} part(s) of {man.get('subject', '?')}")

    failed = []
    for i, p in enumerate(parts, 1):
        out = os.path.join(a.out, p["id"])
        if os.path.exists(os.path.join(out, "views", "right.png")):
            print(f"[{i}/{len(parts)}] {p['id']}: already done, skipping")
            continue
        prompt = (f"A single isolated 3D game asset component: {p['prompt']}. "
                  f"Style: {style}. The component ALONE, floating, detached from "
                  f"any vehicle or character, nothing else in the frame, plain "
                  f"pure white background, no ground, no shadow.")
        print(f"[{i}/{len(parts)}] {p['id']} — {p['label']}")
        r = subprocess.run([sys.executable, os.path.join(HERE, "gen_views.py"),
                            "--kind", "part", "--reference", a.master,
                            "--prompt", prompt, "--out", out])
        if r.returncode:
            print(f"  !! {p['id']} FAILED")
            failed.append(p["id"])
    if failed:
        print(f"FAILED PARTS: {','.join(failed)} — rerun with --only {','.join(failed)}")
        sys.exit(1)
    print("KIT VIEWS DONE — inspect every part before spending GPU time.")


if __name__ == "__main__":
    main()
